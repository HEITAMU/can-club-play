// One GLSL mixing function is embedded in both the Creator .effect and the
// source-runtime descriptor. Keep authored texture samples in their stored
// color space, as the original Canvas 2D painter did.
export const PAINTED_EFFECT_NAME = 'canclub-painted-blend';
export const PAINTED_MIX_GLSL = `
vec4 mixPaintedSamples(vec4 first, vec4 second, vec4 parameters) {
  float firstAlpha = first.a * parameters.x * parameters.z;
  float secondAlpha = second.a * parameters.y * parameters.z;
  vec4 firstPremultiplied = vec4(first.rgb * firstAlpha, firstAlpha);
  vec4 secondPremultiplied = vec4(second.rgb * secondAlpha, secondAlpha);
  vec4 over = secondPremultiplied + firstPremultiplied * (1.0 - secondAlpha);
  vec4 lighter = firstPremultiplied + secondPremultiplied;
  return clamp(mix(over, lighter, parameters.w), 0.0, 1.0);
}`;

export function paintedEffectSource() {
  return `// Generated by scripts/build-painted-effect.mjs from vendor/painted-blend-shader.mjs.
// Hero drawings: transparent lighter. Enemies/carriers: ordered source-over.
CCEffect %{
  techniques:
  - passes:
    - vert: painted-vs:vert
      frag: painted-fs:frag
      depthStencilState:
        depthTest: false
        depthWrite: false
      blendState:
        targets:
        - blend: true
          blendSrc: one
          blendDst: one_minus_src_alpha
          blendSrcAlpha: one
          blendDstAlpha: one_minus_src_alpha
      rasterizerState:
        cullMode: none
      properties:
        secondaryTexture: { value: white }
        secondaryUV: { value: [1, 1, 0, 0] }
        blendParameters: { value: [1, 0, 1, 1] }
}%

CCProgram painted-vs %{
  precision highp float;
  #include <builtin/uniforms/cc-global>
  in vec3 a_position;
  in vec2 a_texCoord;
  in vec4 a_color;
  out vec2 v_uv;
  out vec4 v_color;
  vec4 vert () {
    v_uv = a_texCoord;
    v_color = a_color;
    return cc_matViewProj * vec4(a_position, 1.0);
  }
}%

CCProgram painted-fs %{
  precision highp float;
  in vec2 v_uv;
  in vec4 v_color;
  #pragma builtin(local)
  layout(set = 2, binding = 12) uniform sampler2D cc_spriteTexture;
  uniform sampler2D secondaryTexture;
  uniform PaintedBlend {
    vec4 secondaryUV;
    vec4 blendParameters;
  };
${PAINTED_MIX_GLSL}
  vec4 frag () {
    vec4 first = texture(cc_spriteTexture, v_uv);
    vec4 second = texture(secondaryTexture, v_uv * secondaryUV.xy + secondaryUV.zw);
    vec4 c = mixPaintedSamples(first, second, blendParameters);
    c.rgb *= v_color.rgb * v_color.a;
    c.a *= v_color.a;
    return c;
  }
}%
`;
}

export function registerPaintedBlend(cc, chunks) {
  const {gfx, EffectAsset} = cc;
  const existing = EffectAsset.get(PAINTED_EFFECT_NAME);
  if (existing) return existing;
  const clean = source => source.replace(/\/\/[^\n]*/g, '').replace(/#pragma[^\n]*/g, '').replace(/layout\([^)]*\)\s*/g, '');
  const uniforms = (source, gl3) => gl3
    ? source.replace(/uniform\s+(\w+)\s*\{/g, 'layout(std140) uniform $1 {')
    : source.replace(/uniform\s+\w+\s*\{([\s\S]*?)\};/g, (_, body) => body.split(';').map(s => s.trim()).filter(Boolean).map(s => 'uniform ' + s + ';').join('\n'));
  const globalBlock = clean(chunks['cc-global']);
  const blendBlock = 'uniform PaintedBlend { vec4 secondaryUV; vec4 blendParameters; };';
  const program = gl3 => {
    const input = gl3 ? 'in' : 'attribute', varying = gl3 ? 'out' : 'varying', fragInput = gl3 ? 'in' : 'varying', sample = gl3 ? 'texture' : 'texture2D';
    return {
      vert: `precision highp float;\n${uniforms(globalBlock, gl3)}\n${input} vec3 a_position;\n${input} vec2 a_texCoord;\n${input} vec4 a_color;\n${varying} vec2 v_uv;\n${varying} vec4 v_color;\nvoid main(){v_uv=a_texCoord;v_color=a_color;gl_Position=cc_matViewProj*vec4(a_position,1.0);}`,
      frag: `precision highp float;\n${fragInput} vec2 v_uv;\n${fragInput} vec4 v_color;\nuniform sampler2D cc_spriteTexture;\nuniform sampler2D secondaryTexture;\n${uniforms(blendBlock, gl3)}\n${gl3 ? 'out vec4 fragColor;' : ''}\n${PAINTED_MIX_GLSL}\nvoid main(){vec4 first=${sample}(cc_spriteTexture,v_uv);vec4 second=${sample}(secondaryTexture,v_uv*secondaryUV.xy+secondaryUV.zw);vec4 c=mixPaintedSamples(first,second,blendParameters);c.rgb*=v_color.rgb*v_color.a;c.a*=v_color.a;${gl3 ? 'fragColor' : 'gl_FragColor'}=c;}`,
    };
  };
  const builtins = (blocks=[], textures=[]) => ({buffers:[], blocks:blocks.map(name=>({name,defines:[]})),samplerTextures:textures.map(name=>({name,defines:[]})),images:[]});
  const attributes = [['a_position',gfx.Format.RGB32F],['a_texCoord',gfx.Format.RG32F],['a_color',gfx.Format.RGBA32F]].map(([name,format],location)=>({name,format,location,isNormalized:false,stream:0,isInstanced:false,defines:[]}));
  const effect = new EffectAsset();
  effect.name = PAINTED_EFFECT_NAME;
  const shader = {
    name:'canclub/painted-blend',hash:0x43425032,
    glsl1:program(false),glsl3:program(true),glsl4:program(true),
    builtins:{globals:builtins(['CCGlobal','CCCamera']),locals:builtins([],['cc_spriteTexture']),statistics:{}},
    defines:[],attributes,
    blocks:[{binding:0,name:'PaintedBlend',members:[{name:'secondaryUV',type:gfx.Type.FLOAT4,count:1},{name:'blendParameters',type:gfx.Type.FLOAT4,count:1}],stageFlags:gfx.ShaderStageFlagBit.FRAGMENT}],
    samplerTextures:[{binding:1,name:'secondaryTexture',type:gfx.Type.SAMPLER2D,count:1,stageFlags:gfx.ShaderStageFlagBit.FRAGMENT,sampleType:gfx.SampleType.FLOAT}],
    samplers:[],textures:[],buffers:[],images:[],subpassInputs:[],descriptors:[],
  };
  effect.shaders=[shader];
  effect.techniques=[{passes:[{
    program:shader.name,
    properties:{secondaryTexture:{type:gfx.Type.SAMPLER2D,value:'white'},secondaryUV:{type:gfx.Type.FLOAT4,value:[1,1,0,0]},blendParameters:{type:gfx.Type.FLOAT4,value:[1,0,1,1]}},
    rasterizerState:{cullMode:gfx.CullMode.NONE},depthStencilState:{depthTest:false,depthWrite:false},
    blendState:{targets:[{blend:true,blendSrc:gfx.BlendFactor.ONE,blendDst:gfx.BlendFactor.ONE_MINUS_SRC_ALPHA,blendSrcAlpha:gfx.BlendFactor.ONE,blendDstAlpha:gfx.BlendFactor.ONE_MINUS_SRC_ALPHA}]},
  }]}];
  effect.onLoaded();
  return effect;
}
